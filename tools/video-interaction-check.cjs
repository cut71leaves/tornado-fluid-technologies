const root=path.resolve(__dirname,'..');
const out=path.resolve(process.env.VIDEO_CHECK_OUT||path.join(root,'work/video-checks'));
fs.mkdirSync(out,{recursive:true});
const server=http.createServer((req,res)=>{
  const file=path.resolve(root,'.'+decodeURIComponent(new URL(req.url,'http://localhost').pathname));
  if(!file.startsWith(root+path.sep)||!fs.existsSync(file)||!fs.statSync(file).isFile()){res.writeHead(404);return res.end();}
  const length=fs.statSync(file).size,range=req.headers.range?.match(/^bytes=(\d+)-(\d*)$/);
  const type={'.html':'text/html;charset=utf-8','.js':'text/javascript','.css':'text/css','.mp4':'video/mp4','.webp':'image/webp','.svg':'image/svg+xml'}[path.extname(file)]||'application/octet-stream';
  if(range){const start=+range[1],end=range[2]?Math.min(+range[2],length-1):length-1;res.writeHead(206,{'Content-Type':type,'Accept-Ranges':'bytes','Content-Range':`bytes ${start}-${end}/${length}`,'Content-Length':end-start+1});return fs.createReadStream(file,{start,end}).pipe(res);}
  res.writeHead(200,{'Content-Type':type,'Content-Length':length,'Accept-Ranges':'bytes'});fs.createReadStream(file).pipe(res);
});
